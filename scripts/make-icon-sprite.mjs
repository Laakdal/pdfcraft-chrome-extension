// Builds extension/icons/ui.svg, an SVG sprite of the Lucide icons the extension UI uses, from
// PdfCraft's copy of Lucide (assets/icons/ in the PdfCraft source tree, ISC licence), so the
// extension shows the same icons as PdfCraft.
//
//   node scripts/make-icon-sprite.mjs <pdfcraft-source>/assets/icons

import { copyFileSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

/** sprite id -> Lucide icon name */
const ICONS = {
  'folder-open': 'folder-open',
  download: 'file-down',
  more: 'ellipsis-vertical',
  external: 'external-link',
  link: 'link',
  settings: 'settings',
  alert: 'triangle-alert',
  close: 'x',
  file: 'file-text',
  edit: 'file-pen-line',
  comment: 'message-square',
  sign: 'signature',
  organize: 'files',
  ocr: 'scan-text',
  compress: 'gauge',
  print: 'printer',
  export: 'file-output',
  redact: 'shield-check',
  forms: 'text-cursor-input',
  compare: 'git-compare',
  help: 'circle-help',
  check: 'check',
  chevron: 'chevron-right',
  globe: 'globe',
  lock: 'lock',
  offline: 'cloud',
};

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const icons = process.argv[2];
if (!icons) {
  console.error('usage: node scripts/make-icon-sprite.mjs <pdfcraft-source>/assets/icons');
  process.exit(1);
}

const symbols = Object.entries(ICONS).map(([id, name]) => {
  const svg = readFileSync(join(icons, `${name}.svg`), 'utf8');
  const body = /<svg[^>]*>([\s\S]*)<\/svg>/.exec(svg)?.[1];
  if (!body) throw new Error(`${name}.svg: no <svg> body`);
  return `  <symbol id="${id}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><!-- lucide:${name} -->${body.replace(/\s+/g, ' ').trim()}</symbol>`;
});

const sprite = `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">
  <!-- Lucide icons (https://lucide.dev), ISC License: see LICENSE-lucide.txt. Generated by scripts/make-icon-sprite.mjs. -->
${symbols.join('\n')}
</svg>
`;
writeFileSync(join(root, 'extension', 'icons', 'ui.svg'), sprite);
copyFileSync(join(icons, 'LICENSE-lucide.txt'), join(root, 'extension', 'icons', 'LICENSE-lucide.txt'));
console.log(`extension/icons/ui.svg: ${symbols.length} icons`);
